/**
 * Pure runtime helpers for the pi-gsd-core extension. Everything here is
 * side-effect free (paths and env in, data out) so tests can exercise the
 * host-detection and wiring logic without touching the filesystem.
 */

import path from "node:path";

export type HostRuntime = "omp" | "pi";

export interface RuntimePaths {
  /** Shared runtime root — `~/.gsd` unless GSD_RUNTIME_ROOT overrides it. */
  root: string;
  /** `<root>/bin` — holds the generated gsd-tools launcher. */
  binDir: string;
  /** `<root>/cache` — update-check bookkeeping. */
  cacheDir: string;
  /** `<root>/gsd-core` — symlink target pointing at the engine tree. */
  coreLink: string;
  /** `<root>/bin/gsd-tools` — the launcher script itself. */
  launcher: string;
}

/** Env vars any omp release may set; the first hit wins detection. */
const OMP_ENV_MARKERS = [
  "OMP_APP_NAME",
  "OMP_LIB",
  "OMP_DAEMON_PROJECT_DIR",
  "OMP_AUTH_BROKER_URL",
  "OMP_SESSION_PIN",
];

/**
 * Decide which host loaded us. Precedence:
 *  1. GSD_HOST_RUNTIME override (the documented escape hatch),
 *  2. OMP_* environment markers,
 *  3. execPath/argv probe (the omp binary runs extensions in-process, so
 *     execPath is the omp binary; pi runs through node/bun with a pi argv),
 *  4. default "pi".
 */
export function detectRuntime(
  env: NodeJS.ProcessEnv = process.env,
  argv: string[] = process.argv,
  execPath: string = process.execPath,
): HostRuntime {
  const forced = (env.GSD_HOST_RUNTIME ?? "").toLowerCase();
  if (forced === "omp" || forced === "pi") return forced;
  if (OMP_ENV_MARKERS.some((key) => Boolean(env[key]))) return "omp";
  const probe = `${execPath} ${argv.join(" ")}`;
  if (/(^|\/)omp(\.\w+)?(\s|$)/.test(probe)) return "omp";
  return "pi";
}

export function runtimePaths(env: NodeJS.ProcessEnv = process.env): RuntimePaths {
  const root = path.resolve(env.GSD_RUNTIME_ROOT || path.join(env.HOME || process.env.HOME || "", ".gsd"));
  const binDir = path.join(root, "bin");
  const cacheDir = path.join(root, "cache");
  return {
    root,
    binDir,
    cacheDir,
    coreLink: path.join(root, "gsd-core"),
    launcher: path.join(binDir, "gsd-tools"),
  };
}

/**
 * The `gsd-tools` launcher shell script. Bakes the interpreter path (bun or
 * node — whatever the host runs extensions with), the engine CLI path, and
 * the GSD_RUNTIME id, so vendored skill references to `~/.gsd/bin/gsd-tools`
 * resolve identically on every machine.
 */
export function launcherScript(nodeExecPath: string, engineCli: string, host: HostRuntime): string {
  return [
    "#!/bin/sh",
    `# Generated by pi-gsd-core — rewritten on extension load; do not edit.`,
    `GSD_RUNTIME="${host}" exec "${nodeExecPath}" "${engineCli}" "$@"`,
    "",
  ].join("\n");
}

/** Parse a strict `major.minor.patch` version; null otherwise. */
export function parseSemver(value: unknown): { major: number; minor: number; patch: number } | null {
  const match = /^(\d+)\.(\d+)\.(\d+)$/.exec(String(value ?? "").trim());
  return match ? { major: Number(match[1]), minor: Number(match[2]), patch: Number(match[3]) } : null;
}

/** True when semver a > semver b (strictly). */
export function semverGt(a: unknown, b: unknown): boolean {
  const pa = parseSemver(a);
  const pb = parseSemver(b);
  if (!pa || !pb) return false;
  if (pa.major !== pb.major) return pa.major > pb.major;
  if (pa.minor !== pb.minor) return pa.minor > pb.minor;
  return pa.patch > pb.patch;
}

export interface AgentsSyncPlan {
  /** agent file name → content that must be written into the target dir. */
  writes: Map<string, string>;
  /** file names previously managed by us that vanished upstream. */
  removals: string[];
  /** names already present and byte-identical — no write needed. */
  unchanged: string[];
}

/**
 * Plan the pi agents mirror. Only files the previous manifest tracks are
 * eligible for removal, so directories shared with other tools are never
 * pruned beyond our own namespace (all `gsd-*.md`).
 */
export function planAgentsSync(
  vendored: Map<string, string>,
  targetDir: string,
  previous: { files?: Record<string, string> } | null,
  readTarget: (name: string) => string | null,
): AgentsSyncPlan {
  const writes = new Map<string, string>();
  const unchanged: string[] = [];
  for (const [name, content] of vendored) {
    if (readTarget(path.join(targetDir, name)) === content) unchanged.push(name);
    else writes.set(name, content);
  }
  const previousNames = Object.keys(previous?.files ?? {});
  const removals = previousNames.filter((name) => !vendored.has(name));
  return { writes, removals, unchanged };
}

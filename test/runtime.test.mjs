import test from 'node:test';
import assert from 'node:assert/strict';
import {
  detectRuntime,
  launcherScript,
  parseSemver,
  planAgentsSync,
  runtimePaths,
  semverGt,
} from '../extensions/lib/runtime.ts';

test('detectRuntime honors the GSD_HOST_RUNTIME override first', () => {
  assert.equal(detectRuntime({ GSD_HOST_RUNTIME: 'omp' }, [], '/usr/bin/node'), 'omp');
  assert.equal(detectRuntime({ GSD_HOST_RUNTIME: 'pi' }, [], '/opt/homebrew/bin/omp'), 'pi');
  assert.equal(detectRuntime({ GSD_HOST_RUNTIME: 'nonsense' }, [], '/usr/bin/node'), 'pi');
});

test('detectRuntime recognizes omp via env markers', () => {
  assert.equal(detectRuntime({ OMP_APP_NAME: 'omp' }, [], '/usr/local/bin/bun'), 'omp');
});

test('detectRuntime recognizes the omp binary in execPath', () => {
  assert.equal(detectRuntime({}, [], '/opt/homebrew/bin/omp'), 'omp');
  assert.equal(detectRuntime({}, ['node', '/x/pi'], '/usr/local/bin/bun'), 'pi');
});

test('detectRuntime defaults to pi', () => {
  assert.equal(detectRuntime({}, [], '/usr/local/bin/bun'), 'pi');
});

test('runtimePaths uses HOME/.gsd and honors GSD_RUNTIME_ROOT', () => {
  const home = runtimePaths({ HOME: '/home/u' });
  assert.equal(home.root, '/home/u/.gsd');
  assert.equal(home.launcher, '/home/u/.gsd/bin/gsd-tools');
  assert.equal(home.coreLink, '/home/u/.gsd/gsd-core');

  const custom = runtimePaths({ GSD_RUNTIME_ROOT: '/tmp/gsd-root' });
  assert.equal(custom.root, '/tmp/gsd-root');
});

test('launcherScript bakes interpreter, engine cli, and host runtime', () => {
  const script = launcherScript('/usr/bin/node', '/engine/gsd-core/bin/gsd-tools.cjs', 'omp');
  assert.match(script, /^#!\/bin\/sh\n/);
  assert.match(script, /GSD_RUNTIME="omp" exec "\/usr\/bin\/node" "\/engine\/gsd-core\/bin\/gsd-tools\.cjs" "\$@"/);
  assert.match(script, /Generated by pi-gsd-core/);
});

test('parseSemver and semverGt compare strictly', () => {
  assert.deepEqual(parseSemver('1.13.0'), { major: 1, minor: 13, patch: 0 });
  assert.equal(parseSemver('v1.2.3'), null);
  assert.equal(parseSemver('1.2'), null);
  assert.equal(semverGt('1.14.0', '1.13.0'), true);
  assert.equal(semverGt('1.13.0', '1.13.0'), false);
  assert.equal(semverGt('1.13.0', '1.14.0'), false);
  assert.equal(semverGt('2.0.0', '1.99.99'), true);
  assert.equal(semverGt('junk', '1.0.0'), false);
});

test('planAgentsSync writes new and changed, keeps identical, removes only tracked', () => {
  const targetDir = '/fake/target';
  const vendored = new Map([
    ['gsd-a.md', 'content-a'],
    ['gsd-b.md', 'content-b2'],
  ]);
  const previous = { files: { 'gsd-b.md': 'x', 'gsd-gone.md': 'y' } };
  const readTarget = (file) => (file === `${targetDir}/gsd-a.md` ? 'content-a' : null);

  const plan = planAgentsSync(vendored, targetDir, previous, readTarget);
  assert.deepEqual([...plan.writes.keys()], ['gsd-b.md']);
  assert.deepEqual(plan.unchanged, ['gsd-a.md']);
  assert.deepEqual(plan.removals, ['gsd-gone.md']);
});

test('planAgentsSync never removes files it did not previously track', () => {
  const vendored = new Map([['gsd-a.md', 'a']]);
  const plan = planAgentsSync(vendored, '/t', null, () => null);
  assert.equal(plan.removals.length, 0);
});
